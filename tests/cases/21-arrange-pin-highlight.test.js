const { run } = require("../harness");
const wait = ms => new Promise(r => setTimeout(r, ms));
(async () => {
  const errors = [];
  let { E, p } = await run({}); p.catch(e => errors.push("SCRIPT " + e.stack)); await wait(250);
  let w = E.getDom().window, d = w.document;
  const tap = sel => { const el = typeof sel === "string" ? d.querySelector(sel) : sel; if (!el) throw new Error("no element " + sel); el.dispatchEvent(new w.MouseEvent("click", { bubbles: true })); };
  tap('[data-act="addopen"]'); await wait(30);
  tap('[data-act="addto"][data-v="watch"]'); await wait(10);
  d.querySelector("#paste").value = "AAPL\nMSFT\nKO\nJNJ\nASML"; tap('[data-act="paste"]'); await wait(900);
  tap('[data-act="addclose"]'); await wait(30);
  tap('[data-act="tab"][data-v="watch"]'); await wait(30);
  const order = () => [...d.querySelectorAll(".rows .row")].map(r => r.dataset.v + (r.classList.contains("hl") ? "★" : "") + (r.querySelector(".r-l .pin-i") ? "📌" : "")).join(" ");
  console.log("A sorts:", [...d.querySelectorAll(".listbar .seg button")].map(b => b.textContent).join(" | "), "| order:", order());
  tap('[data-act="arrange"][data-v="1"]'); await wait(30);
  console.log("B arrange:", d.querySelector(".arr-bar span").textContent, "| rows:", d.querySelectorAll(".row.arr .drag-h").length, "| sort now:", JSON.parse(E.files["/docs/Stockit/settings.json"]).sort);
  // what a drag sends: KO to the top, then JNJ second
  w.__nav("stockit://a?d=" + encodeURIComponent(JSON.stringify({ type: "reorder", v: "watch", order: ["KO", "JNJ", "AAPL", "MSFT", "ASML"] }))); await wait(60);
  console.log("C after reorder:", order(), "| saved:", JSON.parse(E.files["/docs/Stockit/stocks.json"]).map(x => x.s).join(" "));
  tap('.row.arr[data-v="ASML"] [data-k="pin"]'); await wait(40);
  tap('.row.arr[data-v="MSFT"] [data-k="hl"]'); await wait(40);
  console.log("D pinned ASML, highlighted MSFT:", order());
  tap('[data-act="arrange"][data-v="0"]'); await wait(30);
  console.log("E done (Mine):", order());
  tap('[data-act="sort"][data-v="az"]'); await wait(30);
  console.log("  A–Z keeps pins first:", order());
  tap('.row[data-v="MSFT"]'); await wait(60);
  console.log("F stock page buttons:", [...d.querySelectorAll('#detail [data-act="mark"]')].map(b => b.textContent).join(" | "));
  tap('#detail [data-act="mark"][data-k="pin"]'); await wait(40); tap('[data-act="close"]'); await wait(20);
  console.log("  after pinning MSFT from its page:", order());
  E.finish(); await p;
  const st = JSON.parse(E.files["/docs/Stockit/stocks.json"]);
  console.log("G saved:", st.map(x => x.s + (x.pin ? "📌" : "") + (x.hl ? "★" : "")).join(" "));
  ({ E, p } = await run({ files: E.files, kc: E.kc })); await wait(300); w = E.getDom().window; d = w.document;
  tap('[data-act="tab"][data-v="watch"]'); await wait(30); tap('[data-act="sort"][data-v="mine"]'); await wait(30);
  console.log("H reopened (Mine):", order());
  E.finish(); await p;
  console.log("errors:", errors.length ? errors.join("; ") : "none", "| JS errors:", E.log.jsErrors || "none");
  process.exit(0);
})().catch(e => { console.log("CRASH", e.stack); process.exit(1); });
